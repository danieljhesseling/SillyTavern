/**
 * The objectives of a board, as rows you can edit.
 *
 * Until now a mission could be written in exactly two ways: by hand in World Info, field
 * by field, or by importing a book. Neither helps somebody who has a board and wants it
 * to be *about* something. This turns the objectives into rows with the fields their type
 * actually asks for, and back again.
 *
 * It is the same translation the pack importer does, and deliberately so: the author
 * writes **names** — "Guardián del grano" — and the engine judges by **ids**, because an
 * objective points at a Lorebook entry. Doing the translation in one shared shape means
 * an objective written by hand, imported from a book or generated by a model is the same
 * object by the time the engine sees it.
 *
 * Pure. See wiki/ROADMAP.md, Fase E · Fase F · wiki/POR_HACER.md.
 */

import { OBJECTIVE_TYPES } from './scenarios.js';
import { OBJECTIVE_FIELDS } from './campaign-pack-schema.js';

/**
 * @typedef {Object} ObjectiveRow
 * @property {string} id
 * @property {string} type
 * @property {string} label
 * @property {boolean} optional
 * @property {Record<string, any>} values What this type asks for, in the author's terms.
 */

/**
 * The fields a type asks the author for, with their help text.
 *
 * Read from the same table the contract publishes, so a new objective type is declared
 * once and every editor learns about it.
 *
 * @param {string} type
 * @returns {Array<{writes: string, engineField: string, kind: string, help: string}>}
 */
export function fieldsFor(type) {
    return OBJECTIVE_FIELDS[String(type ?? '')] ?? [];
}

/** Every type the engine can judge, with its label. */
export function objectiveTypeOptions() {
    return Object.entries(OBJECTIVE_TYPES).map(([id, info]) => ({
        id,
        label: String(/** @type {any} */ (info)?.label ?? id),
        description: String(/** @type {any} */ (info)?.description ?? ''),
    }));
}

/**
 * @param {any} value
 * @returns {string}
 */
function text(value) {
    return String(value ?? '').trim();
}

/**
 * Read a board's objectives into editable rows, turning ids back into names.
 *
 * An objective saved by the importer points at Lorebook uids. Showing those to somebody
 * editing a mission would be showing them the plumbing, so they are translated back using
 * the same table the whole pipeline shares.
 *
 * @param {any[]} objectives
 * @param {Record<string, string>} [namesById] Uid to the name it belongs to.
 * @returns {ObjectiveRow[]}
 */
export function toRows(objectives, namesById = {}) {
    const names = new Map(Object.entries(namesById ?? {}).map(([id, name]) => [String(id), String(name)]));
    const nameOf = (/** @type {any} */ id) => names.get(String(id)) ?? String(id ?? '');

    return (Array.isArray(objectives) ? objectives : []).filter(Boolean).map((objective, index) => {
        const type = text(objective.type) || 'eliminate_all';
        /** @type {Record<string, any>} */
        const values = {};

        for (const field of fieldsFor(type)) {
            const stored = objective[field.engineField];
            if (field.kind === 'name') {
                values[field.writes] = Array.isArray(stored) ? stored.map(nameOf).join(', ') : nameOf(stored);
            } else if (field.kind === 'cell') {
                const cell = stored ?? {};
                values[field.writes] = { x: Number(cell.x) || 0, y: Number(cell.y) || 0 };
            } else {
                values[field.writes] = stored ?? '';
            }
        }

        return {
            id: text(objective.id) || `obj_${index + 1}`,
            type,
            label: text(objective.label) || type,
            optional: Boolean(objective.optional),
            values,
        };
    });
}

/**
 * Turn the rows back into what the engine judges, resolving names to ids.
 *
 * A name nobody knows is reported rather than saved as an empty field: an objective
 * pointing at nobody is a mission that can never be completed and never says why. That
 * mistake has been made once already in this project, and the report is what stops it
 * being made quietly.
 *
 * @param {ObjectiveRow[]} rows
 * @param {Record<string, string>} [idsByName] Name to the uid it belongs to.
 * @returns {{objectives: any[], problems: string[]}}
 */
export function fromRows(rows, idsByName = {}) {
    const ids = new Map(Object.entries(idsByName ?? {}).map(([name, id]) => [name.toLowerCase(), String(id)]));
    /** @type {string[]} */
    const problems = [];

    const objectives = (Array.isArray(rows) ? rows : []).filter(Boolean).map((row, index) => {
        const type = text(row.type) || 'eliminate_all';
        /** @type {any} */
        const built = {
            id: text(row.id) || `obj_${index + 1}`,
            type,
            label: text(row.label) || type,
            optional: Boolean(row.optional),
        };

        for (const field of fieldsFor(type)) {
            const value = row.values?.[field.writes];

            if (field.kind === 'name') {
                const written = text(value).split(',').map(n => n.trim()).filter(Boolean);
                /** @type {string[]} */
                const resolved = [];
                for (const name of written) {
                    const id = ids.get(name.toLowerCase());
                    if (!id) {
                        problems.push(`"${name}" no existe en este mundo (objetivo "${built.label}").`);
                        continue;
                    }
                    resolved.push(id);
                }
                if (resolved.length === 0 && written.length === 0) {
                    problems.push(`Falta ${field.writes} en el objetivo "${built.label}".`);
                }
                built[field.engineField] = field.engineField.endsWith('Ids') ? resolved : (resolved[0] ?? '');
            } else if (field.kind === 'cell') {
                built[field.engineField] = { x: Number(value?.x) || 0, y: Number(value?.y) || 0 };
            } else {
                const n = Number(value);
                if (!Number.isFinite(n) || n <= 0) {
                    problems.push(`${field.writes} tiene que ser un número mayor que cero (objetivo "${built.label}").`);
                }
                built[field.engineField] = Number.isFinite(n) ? n : 0;
            }
        }

        return built;
    });

    return { objectives, problems };
}

/**
 * The JSON schema a model is asked to fill when it writes a mission.
 *
 * Built from the engine's own objective types and their fields, like everything else
 * here: a type added to `scenarios.js` is offered to the model without touching this.
 *
 * @returns {any}
 */
export function buildObjectiveSchema() {
    /** @type {any} */
    const properties = {
        type: { type: 'string', enum: Object.keys(OBJECTIVE_TYPES) },
        label: { type: 'string', description: 'Lo que el jugador lee. Una frase corta, en español.' },
        optional: { type: 'boolean', description: 'true si paga pero no bloquea.' },
    };

    for (const fields of Object.values(OBJECTIVE_FIELDS)) {
        for (const field of fields) {
            if (properties[field.writes]) continue;
            properties[field.writes] = field.kind === 'cell'
                ? { type: 'object', properties: { x: { type: 'integer' }, y: { type: 'integer' } }, description: field.help }
                : field.kind === 'number'
                    ? { type: 'integer', description: field.help }
                    : { type: 'string', description: field.help };
        }
    }

    return {
        type: 'object',
        properties: {
            objectives: {
                type: 'array',
                minItems: 1,
                maxItems: 4,
                items: { type: 'object', properties, required: ['type', 'label'] },
            },
        },
        required: ['objectives'],
    };
}

/**
 * What to ask a model for, given the board it is writing a mission for.
 *
 * It is told the names it may use, because the only failure that matters here is naming
 * somebody who does not exist: everything else is taste, and taste can be edited.
 *
 * @param {Object} input
 * @param {string} input.boardName
 * @param {string[]} [input.enemies]
 * @param {string[]} [input.allies]
 * @param {number} [input.width]
 * @param {number} [input.height]
 * @param {string} [input.idea]
 * @returns {{systemPrompt: string, prompt: string}}
 */
export function buildObjectivePrompt({ boardName, enemies = [], allies = [], width = 0, height = 0, idea = '' }) {
    const systemPrompt = [
        'Eres un diseñador de misiones de rol táctico. Devuelves únicamente JSON válido que cumpla el esquema.',
        'Entre una y tres misiones para un solo tablero, y como mucho una opcional.',
        'Usa exclusivamente los nombres que se te den: inventar uno hace la misión imposible de cumplir.',
        width && height ? `El tablero mide ${width} por ${height} casillas, contando desde 0.` : '',
        enemies.length > 0 ? `Enemigos en el tablero: ${enemies.join(', ')}.` : 'No hay enemigos en el tablero.',
        allies.length > 0 ? `Aliados y compañeros: ${allies.join(', ')}.` : '',
        'Escribe las etiquetas en español, cortas, como las leería un jugador.',
    ].filter(Boolean).join('\n');

    const clean = text(idea).slice(0, 400);
    const prompt = clean
        ? `Escribe los objetivos del tablero "${boardName}" a partir de esta idea: "${clean}"`
        : `Escribe los objetivos del tablero "${boardName}".`;

    return { systemPrompt, prompt };
}

/**
 * Read what the model returned into rows, keeping only what the engine can judge.
 *
 * Anything it invented — a type that does not exist, a name nobody has — is dropped and
 * reported. A generated mission that cannot be completed is worse than none.
 *
 * @param {any} raw
 * @param {{enemies?: string[], allies?: string[]}} [known]
 * @returns {{rows: ObjectiveRow[], warnings: string[]}}
 */
export function normalizeGeneratedObjectives(raw, known = {}) {
    const list = Array.isArray(raw?.objectives) ? raw.objectives : (Array.isArray(raw) ? raw : []);
    const enemies = new Set((known.enemies ?? []).map(n => n.toLowerCase()));
    const allies = new Set((known.allies ?? []).map(n => n.toLowerCase()));

    /** @type {string[]} */
    const warnings = [];
    /** @type {ObjectiveRow[]} */
    const rows = [];

    list.filter(Boolean).forEach((objective, index) => {
        const type = text(objective.type);
        if (!OBJECTIVE_TYPES[type]) {
            warnings.push(`Se descarta un objetivo de tipo "${type || 'sin tipo'}", que el motor no sabe juzgar.`);
            return;
        }

        /** @type {Record<string, any>} */
        const values = {};
        let usable = true;

        for (const field of fieldsFor(type)) {
            const value = objective[field.writes];
            if (field.kind === 'name') {
                const name = text(value);
                const pool = field.engineField === 'allyId' ? allies : enemies;
                if (!name || !pool.has(name.toLowerCase())) {
                    warnings.push(`Se descarta "${text(objective.label) || type}": nombra a "${name || 'nadie'}", que no está en el tablero.`);
                    usable = false;
                    break;
                }
                values[field.writes] = name;
            } else if (field.kind === 'cell') {
                values[field.writes] = { x: Number(value?.x) || 0, y: Number(value?.y) || 0 };
            } else {
                const n = Math.floor(Number(value));
                if (!Number.isFinite(n) || n <= 0) {
                    warnings.push(`Se descarta "${text(objective.label) || type}": ${field.writes} no es un número usable.`);
                    usable = false;
                    break;
                }
                values[field.writes] = n;
            }
        }

        if (!usable) return;

        rows.push({
            id: `gen_${index + 1}`,
            type,
            label: text(objective.label) || String(/** @type {any} */ (OBJECTIVE_TYPES[type])?.label ?? type),
            optional: Boolean(objective.optional),
            values,
        });
    });

    return { rows, warnings };
}

/**
 * Ask a model for the objectives of a board.
 *
 * The same shape as `generateWorld`: the provider is injected, the answer goes through
 * the schema and then through `normalizeGeneratedObjectives`, and what comes back is
 * already rows the editor can show and the player can change. Nothing is saved by this.
 *
 * @param {Object} input
 * @param {(params: any) => Promise<any>} input.generate
 * @param {string} input.boardName
 * @param {string[]} [input.enemies]
 * @param {string[]} [input.allies]
 * @param {number} [input.width]
 * @param {number} [input.height]
 * @param {string} [input.idea]
 * @returns {Promise<{rows: ObjectiveRow[], warnings: string[], errors: string[]}>}
 */
export async function generateObjectives({ generate, boardName, enemies = [], allies = [], width = 0, height = 0, idea = '' }) {
    const { systemPrompt, prompt } = buildObjectivePrompt({ boardName, enemies, allies, width, height, idea });

    let answer;
    try {
        answer = await generate({ prompt, systemPrompt, jsonSchema: buildObjectiveSchema(), responseLength: 800 });
    } catch (error) {
        return { rows: [], warnings: [], errors: [`El proveedor no respondió: ${error?.message || error}`] };
    }

    let parsed = answer;
    if (typeof answer === 'string') {
        try {
            parsed = JSON.parse(answer);
        } catch {
            return { rows: [], warnings: [], errors: ['La respuesta no era JSON válido. Prueba otra vez.'] };
        }
    }

    const { rows, warnings } = normalizeGeneratedObjectives(parsed, { enemies, allies });
    return {
        rows,
        warnings,
        errors: rows.length === 0 ? ['El modelo no devolvió ningún objetivo que el motor pueda juzgar.'] : [],
    };
}
